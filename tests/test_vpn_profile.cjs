const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const source=fs.readFileSync(path.join(__dirname,"../internal/pilot/web/app.js"),"utf8");
const start=source.indexOf("function validateIndependentVPN(");
const end=source.indexOf("function dnsProbePanel(){",start);
assert.ok(start>=0&&end>start);
const validate=new Function(source.slice(start,end)+";return validateIndependentVPN;")();
const key="A".repeat(43)+"=";
const wg="[Interface]\nPrivateKey = "+key+"\nAddress=10.0.0.2/32\n[Peer]\nPublicKey = "+key+"\nEndpoint = example.com:51820\nAllowedIPs = 0.0.0.0/0";
assert.doesNotThrow(()=>validate("ssh",{host:"example.com",user:"root",port:22}));
assert.throws(()=>validate("ssh",{host:"example.com",user:"root",port:70000}));
assert.doesNotThrow(()=>validate("wg",{config:wg}));
assert.throws(()=>validate("wg",{config:wg+"\nPostUp = echo hi"}));
assert.doesNotThrow(()=>validate("awg",{config:wg.replace("[Peer]","Jc=4\n[Peer]")}));
assert.throws(()=>validate("wg",{config:wg.replace("[Peer]","Jc=4\n[Peer]")}));
assert.doesNotThrow(()=>validate("openvpn",{config:"client\nremote example.com 1194"}));
assert.throws(()=>validate("openvpn",{config:"client\nremote example.com 1194\nup /tmp/x"}));
console.log("VPN profile preflight: 8 checks passed");

const previewStart=source.indexOf("function previewLocalSubscription(");
const previewEnd=source.indexOf("function showSubscriptionDialog(",previewStart);
assert.ok(previewStart>=0&&previewEnd>previewStart);
const preview=new Function(source.slice(previewStart,previewEnd)+";return previewLocalSubscription;")();
const sample="vless://dummy@example.com\nss://dummy@example.com\n# comment\ninvalid";
assert.deepEqual(preview(sample),{total:3,types:{vless:1,ss:1},unknown:1});
assert.deepEqual(preview(Buffer.from(sample).toString("base64")) ,preview(sample));
assert.throws(()=>preview("proxies: []"));
console.log("Local VPN preview: 3 checks passed");
